export interface ChapterInfo {
  chapter: string
  order: number
}

// 영어는 null(단어집). 그 외 과목은 {chapter, order}.
export function classifyChapter(subject: string, unit?: string): ChapterInfo | null {
  if (subject === '영어') return null
  const rules = RULES[subject]
  if (!rules) return { chapter: unit?.trim() || '기타', order: 999 }
  const u = (unit ?? '').replace(/\s/g, '')
  if (u) {
    for (let i = 0; i < rules.length; i++) {
      const r = rules[i]!
      if (r.kw.some((k) => u.includes(k.replace(/\s/g, '')))) return { chapter: r.chapter, order: i }
    }
  }
  return { chapter: '기타', order: 998 }
}
